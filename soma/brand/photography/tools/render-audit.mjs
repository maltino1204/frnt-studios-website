// node brand/photography/tools/render-audit.mjs → brand/photography/AUDIT.md (the v1 audit table)
import fs from "node:fs";
import path from "node:path";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../../..");
const lines = fs.readFileSync(path.join(root, "brand/photography/audit/audit-v1.txt"), "utf8").split("\n").filter((l) => l && !l.startsWith("#"));
const recrops = JSON.parse(fs.readFileSync(path.join(root, "brand/photography/audit/recrops.json"), "utf8")).items;
const sources = JSON.parse(fs.readFileSync(path.join(root, "scripts/images/sources.json"), "utf8"));
const repl = Object.fromEntries(sources.filter((s) => s.replacedBy).map((s) => [s.path, s.replacedBy]));
const v1 = sources.filter((s) => !s.source).map((s) => s.path);
const rows = lines.map((l) => { const [p, codes, note] = l.split("|").map((x) => x.trim()); return { p: `/images/${p}.jpg`, codes, note }; });
const missing = v1.filter((p) => !rows.find((r) => r.p === p));
if (missing.length) throw new Error("audit misses " + missing.join(", "));
const count = { keep: 0, recrop: 0, replace: 0 }, codeCount = {};
const out = rows.map((r) => {
  const verdict = repl[r.p] ? "replace" : recrops[r.p] ? "recrop" : "keep";
  count[verdict]++;
  for (const c of r.codes.split(" ").filter((c) => c !== "-")) codeCount[c] = (codeCount[c] ?? 0) + 1;
  const to = verdict === "replace" ? `\`${repl[r.p].replace("/images/", "")}\`` : verdict === "recrop" ? "`-v2` via `recrops.json`" : "–";
  return `| \`${r.p.replace("/images/", "")}\` | **${verdict}** | ${r.codes} | ${r.note} | ${to} |`;
});
const legend = { T: "fake text, logos or UI burnt in", F: "film border or rebate", S: "spa cliché (orchid, candle, stones, cucumber, petals, rolled towels, bamboo)", N: "exposure or sensual crop", C: "clinic or salon look", G: "grading off (green or cool cast)", X: "truth or voice issue", H: "anatomy", P: "posed, stock or beauty-ad look" };
const md = `# SOMA photography: audit of the v1 development set (131 images)

*Digital Art Director · phase B2 · 1 Nov 2026. Generated by \`brand/photography/tools/render-audit.mjs\` from \`audit/audit-v1.txt\`; do not hand-edit.*
*Contact sheets: \`audit/sheets/*.jpg\`. Recrop previews (crop box in Oxblood, result on the right): \`audit/recrops-*.jpg\`.*

## Result

| Verdict | Count | What happens |
|---|---|---|
| **keep** | ${count.keep} | Used as is (development asset, AI label stays). |
| **recrop** | ${count.recrop} | Usable once the AI frame artefacts are cut off. Boxes in \`audit/recrops.json\`; \`node brand/photography/tools/recrops.mjs --apply\` writes \`<name>-v2.jpg\` next to the original. |
| **replace** | ${count.replace} | Regenerated in v2 (\`replacedBy\` in \`scripts/images/sources.json\`). The v1 file stays until the app switches. |

| Code | Issue | Images |
|---|---|---|
${Object.entries(legend).map(([c, t]) => `| ${c} | ${t} | ${codeCount[c] ?? 0} |`).join("\n")}

**Root cause.** The v1 prompts ended with *"Avoid: candles, stones, pebbles, orchids …"*. The \`soul_2\` model does not read negations reliably: it rendered the very props the sentence named (${codeCount.S} of 131 images carry one). It also adds film borders, fake captions and UI chrome (${codeCount.T} images), because it imitates social-media photography. v2 therefore uses **positive-only prompts** on \`soul_2\` and **GPT Image 2.5** (which follows exclusions) for every scene with people, props or text-prone surfaces (\`generation/shotlist-v2.mjs\`).

**Never use (pull from every surface now):** \`portfolio/haare-styling-5\`, \`portfolio/make-up-5\`, \`portfolio/massage-4\`, \`portfolio/massage-14\` (nudity), \`portfolio/massage-11\` (couples' massage, not offered), \`editorial/hotel\` (fake signage in the key hotel band).

## All images

| Image | Verdict | Codes | Finding | v2 |
|---|---|---|---|---|
${out.join("\n")}
`;
fs.writeFileSync(path.join(root, "brand/photography/AUDIT.md"), md);
console.log(count, codeCount);
