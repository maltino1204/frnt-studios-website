// node brand/photography/tools/v3-audit.mjs  → brand/photography/AUDIT-v3.md
// Renders the v3 QA record from generation/jobs-v3.json (every job, its verdict and reason), generation/shotlist-v3.mjs
// (entity per image), scripts/images/sources.json (what each v3 file replaces) and v3/luminance.json (tools/v3-luminance.mjs).
// The narrative sections are in tools/v3-audit-notes.md; this script only adds the tables. Do not hand-edit AUDIT-v3.md.
import fs from "node:fs";
import path from "node:path";
import { ALL, SKIPPED, KEYS } from "../generation/shotlist-v3.mjs";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../../..");
const L = JSON.parse(fs.readFileSync(path.join(root, "brand/photography/generation/jobs-v3.json"), "utf8"));
const S = JSON.parse(fs.readFileSync(path.join(root, "scripts/images/sources.json"), "utf8"));
const lum = JSON.parse(fs.readFileSync(path.join(root, "brand/photography/v3/luminance.json"), "utf8"));
const [notes, sheetsSection = ""] = fs.readFileSync(path.join(root, "brand/photography/tools/v3-audit-notes.md"), "utf8").split(/(?=^## 5\. )/m);
const byPath = new Map(S.map((e) => [e.path, e]));
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|");
const short = (p) => p.replace("/images/", "");

const jobs = L.jobs.filter((j) => j.group !== "model-test");
const tests = L.jobs.filter((j) => j.group === "model-test");
const credits = L.jobs.reduce((a, j) => a + (j.credits || 0), 0);
const byShot = new Map();
for (const j of jobs) byShot.set(j.shot, [...(byShot.get(j.shot) ?? []), j]);

const rows = [];
let generated = 0, rejected = 0;
for (const s of ALL) {
  const js = byShot.get(s.id) ?? [];
  generated += js.length;
  const fails = js.filter((j) => j.status === "fail");
  rejected += fails.length;
  const cur = L.current[s.path];
  const final = js.find((j) => j.id === cur?.job);
  const e = byPath.get(s.path);
  rows.push({
    path: s.path, entity: s.entity, replaces: e?.replaces ? short(e.replaces) : "new",
    verdict: final?.status === "pass" ? "**pass**" : final ? `**${final.status ?? "open"}**` : "**open**",
    reason: final?.reason ?? "", rejected: fails.map((j) => `${j.attempt}: ${j.reason}`).join("; "),
    retries: js.length - 1, job: cur?.job ?? "",
  });
}
// derived crops (no own generation)
for (const p of ["/images/hero/home-v3.jpg", "/images/landing/hero-home-4x5-v3.jpg"]) {
  const e = byPath.get(p); const src = L.current["/images/landing/hero-mobile-v3.jpg"];
  rows.push({ path: p, entity: "4:5 crop of landing/hero-mobile-v3 (L02)", replaces: e?.replaces ? short(e.replaces) : "", verdict: "**pass**", reason: "crop checked at its focal point (bright, sheet to the shoulder blades, hands correct)", rejected: "", retries: 0, job: src?.job ?? "" });
}
const finals = rows.length;
const pass = rows.filter((r) => r.verdict === "**pass**").length;
const group = (p) => (p.split("/").length === 3 ? "og" : p.split("/")[2]);
const order = ["pros", "landing", "hero", "editorial", "og", "categories", "explore", "portfolio"];
rows.sort((a, b) => order.indexOf(group(a.path)) - order.indexOf(group(b.path)) || a.path.localeCompare(b.path, "en", { numeric: true }));

let md = `# SOMA photography v3 „Tageslicht“: QA audit\n\n*Photo Art Director · 2 Nov 2026. Generated by \`brand/photography/tools/v3-audit.mjs\` from \`generation/jobs-v3.json\`; do not hand-edit (notes: \`tools/v3-audit-notes.md\`).*\n\n`;
md += `## Result\n\n| | |\n|---|---|\n| Model | **Higgsfield \`nano_banana_pro\`, 2k** (2 credits per image) — chosen in the test below |\n| Credits used | **${credits.toFixed(2)}** of 500 (model test ${tests.reduce((a, j) => a + j.credits, 0).toFixed(2)}, set and retries ${(credits - tests.reduce((a, j) => a + j.credits, 0)).toFixed(2)}) |\n| Generations | **${generated}** for the set (+ ${tests.length} model-test jobs) |\n| Rejected in QA | **${rejected}** (every reason below) |\n| Final files | **${finals}** (${ALL.length} generated paths + 2 derived 4:5 crops); **${pass} pass**, ${finals - pass} open |\n| Skipped by Lead decision | ${SKIPPED.size} landing images (§ 3) |\n\n`;
md += `### Mean luminance per folder, before → after\n\nBefore = the ${lum.before.ALL.n} files in use that v3 replaces; after = the ${lum.after.ALL.n} v3 files and the new covers. Luma: Rec. 709 on sRGB values, 0–255. Near-black: luma < 51 (20 %).\n\n`;
md += `| Folder | Images | Mean luma | Mean L* | Near-black pixels | Darkest image after (luma) |\n|---|---|---|---|---|---|\n`;
for (const k of [...order, "ALL"]) {
  const b = lum.before[k], a = lum.after[k]; if (!b && !a) continue;
  md += `| ${k === "ALL" ? "**All**" : `\`${k}/\``} | ${b?.n ?? "–"} → ${a?.n ?? "–"} | ${b?.luma ?? "–"} → **${a?.luma ?? "–"}** | ${b?.L ?? "–"} → ${a?.L ?? "–"} | ${b?.dark ?? "–"} % → ${a?.dark ?? "–"} % | ${a?.min ?? "–"} |\n`;
}
md += `\n## 1. Model test (Selin A. portrait and a manicure scene, same prompt)\n\n| Model | Target | Credits | Finding |\n|---|---|---|---|\n`;
for (const t of tests) md += `| \`${t.model}\` | ${esc(t.target)} | ${t.credits} | ${esc(t.verdict)} |\n`;
md += `\nSheet: \`v3/00-model-test.jpg\`.\n\n${notes}\n`;
md += `## 3. Skipped by Lead decision (2 Nov 2026)\n\nThe landing chapters 02 (Idee), 05 (Dein Ort, the six-step stage) and 07 (Deine Buchung) are removed. These images were used only there; their \`sources.json\` entries stay as they are (no v3, no \`replacedBy\`):\n\n`;
for (const k of KEYS.filter((k) => SKIPPED.has(k.id))) md += `- \`${short(k.path.replace("-v3.jpg", ".jpg"))}\` (${k.entity})\n`;
md += `\n## 4. Every image\n\nVerdict and reason are for the final file; „rejected“ lists every earlier attempt with its reason (attempt number first). Retries = attempts − 1. Job = the Higgsfield job of the final file.\n\n`;
md += `| v3 file | Entity | Replaces | Verdict | Reason (final) | Rejected attempts | Retries | Job |\n|---|---|---|---|---|---|---|---|\n`;
for (const r of rows) md += `| \`${short(r.path)}\` | ${esc(r.entity)} | \`${esc(r.replaces)}\` | ${r.verdict} | ${esc(r.reason)} | ${esc(r.rejected) || "–"} | ${r.retries} | \`${r.job.slice(0, 8)}\` |\n`;
md += `\n${sheetsSection}`;
fs.writeFileSync(path.join(root, "brand/photography/AUDIT-v3.md"), md);
console.log(`AUDIT-v3.md: ${rows.length} rows, ${pass} pass, ${rejected} rejected attempts, ${credits.toFixed(2)} credits`);
