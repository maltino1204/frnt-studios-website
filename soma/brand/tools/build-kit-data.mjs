// Writes src/app/kit/marke/data.generated.ts: the real artwork (path data) and token values for the
// brand book page, so /kit/marke renders the masters without reading files at runtime.
import fs from "node:fs";
import { toD, transform, bounds } from "./lib/geo.mjs";
import { inkBounds } from "./lib/word.mjs";
import { finalArt, symbolArt, lockups, art } from "./build-logo.mjs";
import * as A from "./concept-a.mjs";
import * as B from "./concept-b.mjs";
import * as C from "./concept-c.mjs";
import * as F from "./final.mjs";
import * as T from "./tokens-source.mjs";
import { fluid } from "./build-tokens.mjs";
import { ICONS, ARCH_RATIO } from "./build-graphics.mjs";

const OUT = new URL("../../src/app/kit/marke/data.generated.ts", import.meta.url).pathname;
const f2 = (v) => +v.toFixed(2);
const vbOf = (a) => a.vb.map(f2);
const pathsOf = (a) => a.items.map((it) => ({ id: it.name.toLowerCase(), d: toD(it.item) }));

const concepts = [
  { key: "A", name: "Architektonisch", mod: A, scores: { originality: 5, elegance: 6, scalability: 9, memorability: 5 },
    idea: "Monolineare, geometrische Versalien auf einer Datum-Linie: Scheitel des M, Querstrich des A und Mitte des S liegen auf derselben Horizontalen bei 0,6 H.",
    verdict: "Präzise und robust bis 16 px, aber nah an bekannten Geometrie-Grotesken; die Datum-Idee bleibt für Laien unsichtbar." },
  { key: "B", name: "Editorial", mod: B, scores: { originality: 5, elegance: 8, scalability: 4, memorability: 6 },
    idea: "Kontrastreiche Antiqua-Versalien mit vertikaler Achse, Haarlinien-Serifen und linsenförmigen Tropfen am S.",
    verdict: "Elegant in Groß, aber das Didone-Vokabular ist das Standardbild von Mode-Magazinen; Haarlinien und Serifen verschwinden unter 24 px." },
  { key: "C", name: "Organische Moderne", mod: C, scores: { originality: 8, elegance: 8, scalability: 7, memorability: 8 },
    idea: "Serifenlos und kontrastreich. Das S ist aus den zwei Hälften des O gebaut, gegeneinander verschoben wie Schulter und Hüfte im Kontrapost.",
    verdict: "Eigenständig, warm und zugleich präzise. Gewählt und verfeinert; ein Mikro-Master sichert die kleinen Größen." },
].map((c) => {
  const a = art(c.mod.word().items);
  return { key: c.key, name: c.name, idea: c.idea, verdict: c.verdict, scores: c.scores, viewBox: vbOf(a), paths: pathsOf(a) };
});

const wm = finalArt("display"), micro = finalArt("micro"), sym = symbolArt("line"), seal = symbolArt("solid");
const L = lockups();
const lock = (l) => ({ viewBox: l.vb.map(f2), groups: l.groups.map((g) => ({ id: g.id, transform: g.transform ?? null, paths: g.paths.map((p) => p.d) })) });
// app icon: the line mark on a 1024 tile, O height 62 % (same as brand/assets/icons/ios/AppIcon.svg)
const mk = F.symbolMark("line");
const sc = (1024 * 0.62) / (2 * F.MARK.ry);
const at = (g) => toD(transform(g, { sx: sc, tx: 512, ty: 512 }));
const icon = [at(mk.o), at(mk.s)];
const P = T.P;
const res = (v) => (P[v] ? P[v] : v);
const semantic = Object.fromEntries(Object.entries(T.semantic).map(([g, e]) => [g, Object.fromEntries(Object.entries(e).map(([k, [v, d]]) => [k, { value: res(v), ref: P[v] ? v : null, note: d }]))]));
const type = Object.fromEntries(Object.entries(T.type).map(([k, [min, max, lh, tr, w, fam, note]]) => [k, { min, max, size: fluid(min, max), lineHeight: lh, tracking: tr, weight: w, family: fam, note }]));
const contrast = JSON.parse(fs.readFileSync(new URL("../DESIGN_TOKENS/contrast.json", import.meta.url), "utf8"));

const data = {
  concepts,
  final: {
    wordmark: { viewBox: vbOf(wm), paths: pathsOf(wm) },
    micro: { viewBox: vbOf(micro), paths: pathsOf(micro) },
    symbol: { viewBox: vbOf(sym), paths: pathsOf(sym) },
    seal: { viewBox: vbOf(seal), paths: pathsOf(seal) },
    descriptor: lock(L.descriptor),
    tagline: lock(L.tagline),
    stacked: lock(L.stacked),
    appIcon: { size: 1024, paths: icon },
    drawOn: JSON.parse(fs.readFileSync(new URL("../assets/splash/soma-mark-draw.json", import.meta.url), "utf8")),
    symbolStudies: JSON.parse(fs.readFileSync(new URL("../assets/logo/concepts/symbol-studies-2.json", import.meta.url), "utf8")).rows,
  },
  palette: Object.fromEntries(Object.entries(T.primitives).map(([k, v]) => [k, { value: v.value, note: v.note ?? null, brand: !!v.brand }])),
  semantic,
  feedback: Object.fromEntries(Object.entries(T.feedback).map(([k, f]) => [k, { fg: P[f.fg], bg: P[f.bg], border: P[f.border], icon: f.icon, word: f.word }])),
  type,
  contrast,
  radii: T.radii,
  shadow: T.shadow,
  motion: T.motion,
  icons: Object.fromEntries(Object.entries(ICONS).map(([k, d]) => [k, d.split("|")])),
  archRatio: ARCH_RATIO,
  tones: Object.fromEntries(Object.entries(T.tones).map(([k, [w, ink]]) => [k, { wash: w, ink: res(ink) }])),
};
const src = `// GENERATED by brand/tools/build-kit-data.mjs. Do not edit: run \`node brand/tools/build-kit-data.mjs\`.\n/* eslint-disable */\nexport const BRAND = ${JSON.stringify(data, null, 1)} as const;\n`;
fs.writeFileSync(OUT, src);
console.log("kit data", (src.length / 1024).toFixed(0), "KB");
