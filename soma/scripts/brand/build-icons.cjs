// Usage (from soma/): node scripts/brand/build-icons.cjs
// Reads the custom brand icons (brand/assets/iconography/custom/*.svg, owned by the Identity Designer) and writes
// src/components/brand/brand-icons.generated.ts for <BrandIcon>. Re-run whenever the masters change.
// Supports the elements the masters use (path, circle, rect, line, ellipse, polyline, polygon) on a 24 px grid.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "../..");
const dir = path.join(root, "brand/assets/iconography/custom");
const out = path.join(root, "src/components/brand/brand-icons.generated.ts");
const TAGS = ["path", "circle", "rect", "line", "ellipse", "polyline", "polygon"];

const icons = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(dir, file), "utf8");
  const vb = /viewBox="([^"]+)"/.exec(svg);
  if (!vb || vb[1].trim() !== "0 0 24 24") throw new Error(`${file}: expected viewBox "0 0 24 24"`);
  const nodes = [];
  const re = new RegExp(`<(${TAGS.join("|")})\\b([^>]*?)/?>`, "g");
  let m;
  while ((m = re.exec(svg))) {
    const attrs = {};
    for (const a of m[2].matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) {
      if (["d", "cx", "cy", "r", "rx", "ry", "x", "y", "x1", "y1", "x2", "y2", "width", "height", "points"].includes(a[1])) attrs[a[1]] = a[2];
    }
    nodes.push([m[1], attrs]);
  }
  if (!nodes.length) throw new Error(`${file}: no drawable elements`);
  icons[file.replace(/\.svg$/, "")] = nodes;
}

const body = `// GENERATED by scripts/brand/build-icons.cjs from brand/assets/iconography/custom/*.svg. Do not edit.
export const BRAND_ICONS = ${JSON.stringify(icons, null, 2)} as const satisfies Record<string, ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>>;
`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(root, out)}: ${Object.keys(icons).join(", ")}`);
